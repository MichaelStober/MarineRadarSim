# ============================================================
# HTTP-Session
# ============================================================

session = requests.Session()

session.headers.update(
    {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 Chrome/140 Safari/537.36"
        )
    }
)


# ============================================================
# Ausgabeordner
# ============================================================

os.makedirs(OUTPUT_DIR, exist_ok=True)


# ============================================================
# Download
# ============================================================

total = len(TILES)
successful = 0
failed = []

print(f"{total} Kacheln zum Download vorbereitet.")
print(f"Zielordner: {os.path.abspath(OUTPUT_DIR)}")
print()


for number, tile in enumerate(TILES, start=1):
    # --------------------------------------------------------
    # Dateiname
    # --------------------------------------------------------

    filename = f"dgm1_{tile}_2_gtiff.tif"

    output_file = os.path.join(OUTPUT_DIR, filename)

    # --------------------------------------------------------
    # URL zusammensetzen
    # --------------------------------------------------------

    url = f"{BASE_URL}?index={INDEX}&dataset={DATASET}&file={filename}&source={SOURCE}"

    print("=" * 70)
    print(f"[{number}/{total}] {tile}")
    print(f"Datei: {filename}")

    # --------------------------------------------------------
    # Bereits vorhanden?
    # --------------------------------------------------------

    if os.path.exists(output_file):
        size_mb = os.path.getsize(output_file) / 1024 / 1024

        print(f"Übersprungen - bereits vorhanden ({size_mb:.1f} MB)")

        successful += 1
        continue

    # --------------------------------------------------------
    # Download
    # --------------------------------------------------------

    try:
        print("Download gestartet ...")

        with session.get(url, stream=True, timeout=(30, 600)) as response:
            response.raise_for_status()

            total_bytes = int(response.headers.get("Content-Length", 0))

            downloaded = 0

            with open(output_file, "wb") as file:
                for chunk in response.iter_content(chunk_size=1024 * 1024):
                    if not chunk:
                        continue

                    file.write(chunk)
                    downloaded += len(chunk)

                    if total_bytes > 0:
                        percent = downloaded / total_bytes * 100

                        print(
                            f"\r"
                            f"{downloaded / 1024 / 1024:.1f} MB "
                            f"/ "
                            f"{total_bytes / 1024 / 1024:.1f} MB "
                            f"({percent:.1f}%)",
                            end="",
                        )

                    else:
                        print(f"\r{downloaded / 1024 / 1024:.1f} MB", end="")

        print()

        size_mb = os.path.getsize(output_file) / 1024 / 1024

        print(f"OK - {size_mb:.1f} MB")

        successful += 1

    except Exception as error:
        print()
        print(f"FEHLER: {error}")

        failed.append(tile)

        # Unvollständige Datei löschen
        if os.path.exists(output_file):
            os.remove(output_file)

    # --------------------------------------------------------
    # Kleine Pause zwischen Downloads
    # --------------------------------------------------------

    time.sleep(0.5)


# ============================================================
# Zusammenfassung
# ============================================================

print()
print("=" * 70)
print("DOWNLOAD ABGESCHLOSSEN")
print("=" * 70)

print(f"Gesamt:      {total}")
print(f"Erfolgreich: {successful}")
print(f"Fehler:      {len(failed)}")

if failed:
    print()
    print("Fehlgeschlagene Kacheln:")

    for tile in failed:
        print(f"  {tile}")

print()
print(f"Dateien liegen in: {os.path.abspath(OUTPUT_DIR)}")
